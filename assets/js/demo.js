// AIにつなぐ前の確認用。答えを少しだけ差し込んだ「見本の文章」を返す。
// 画面にも「見本です」と表示するので、本物の原稿と取り違えることはない。

export function demoDraft(questions, answers) {
  const get = (re) => {
    const q = questions.find(q => re.test(q.text || ""));
    return q ? String(answers[q.id] ?? "").trim() : "";
  };
  const period = get(/時期/) || "あの頃のこと";
  const scene = get(/場面/);
  const name = get(/名前|ペンネーム/) || "わたし";
  const core = period.replace(/^例：/, "").replace(/のこと$/, "");

  const opening = scene
    ? scene.replace(/^例：/, "") + "\n\n"
    : "";

  return [
    "【タイトル案】",
    "1. 暖簾をしまう、その前に ｜ いちばん心に残った夜を入口に、" + core + "をたどる",
    "2. " + core + "の、灯り ｜ 続けてこられた理由を、出会った人から描く",
    "3. まだ、いいかしら ｜ 読んだ人がふっと笑える、あたたかな回想録",
    "",
    "【目次】",
    "第1章　雨の日の、2名さま ｜ 誰も来なかった3日目の夜と、傘をさして入ってきた2人のこと",
    "第2章　40歳の、はじめて ｜ 迷いながら踏み出した日と、背中を押してくれた言葉",
    "第3章　帳簿の数字 ｜ 苦しかった月、救われた月。数字の向こうにいた人たち",
    "第4章　常連さんという家族 ｜ 毎朝同じ席に座る人たちが、教えてくれたこと",
    "第5章　閉める日のこと ｜ 最後の営業日、最後のお客さんとのやりとり",
    "第6章　" + name + "から、あなたへ ｜ この本を手にとった人に、いちばん伝えたいこと",
    "",
    "【冒頭】",
    opening +
    "あの夜のことは、いまでもはっきり覚えている。\n\n" +
    "開店して3日目。朝から窓の外ばかり見ていた。通りを行く人は、店の前で少しだけ歩みをゆるめ、それから何ごともなかったように通り過ぎていく。\n\n" +
    "19時。今日はもう終わりにしよう、と暖簾に手をかけたとき、入口の鈴が鳴った。傘をさしたご婦人が2名、「まだ、いいかしら」と顔をのぞかせた。\n\n" +
    "ありがたい、と思うより先に、これで明日も店を開けられる、と思った。その気持ちが、それからの長い年月を支えてくれたのだと、いまならわかる。\n\n" +
    "（ここから先は、ご自分の言葉で書き足してください）"
  ].join("\n");
}
